"""Write the token layer: _tokens.scss, tokens.css and tokens.json."""

from __future__ import annotations

import json
from pathlib import Path

from .tokens import SCALAR_TABLES, Tokens, contrast_report, css_vars, theme_vars

HEADER = "GENERATED by brand/build.py from brand/tokens.toml. Do not edit; edit tokens.toml."


def _block(selector: str, decls: dict[str, str], extra: str = "", indent: str = "") -> str:
    lines = [f"{indent}{selector} {{"]
    if extra:
        lines.append(f"{indent}  {extra}")
    lines += [f"{indent}  --{k}: {v};" for k, v in decls.items()]
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def root_css(tokens: Tokens) -> str:
    """The custom-property layer shared by tokens.css and _tokens.scss."""
    default = tokens.default_theme
    light = tokens.light_theme
    parts = [
        _block(":root", css_vars(tokens)),
        _block(":root", theme_vars(tokens.themes[default]), _scheme(default)),
    ]
    for name, theme in tokens.themes.items():
        parts.append(_block(f':root[data-theme="{name}"]', theme_vars(theme), _scheme(name)))
    if light != default:
        parts.append(
            "@media (prefers-color-scheme: light) {\n"
            + _block(":root:not([data-theme])", theme_vars(tokens.themes[light]), _scheme(light), "  ")
            + "\n}"
        )
    return "\n\n".join(parts) + "\n"


def _scheme(theme: str) -> str:
    return "color-scheme: light;" if theme == "paper" else "color-scheme: dark;"


def _scss_map(name: str, items: dict[str, str], quote: bool = False) -> str:
    def val(v: str) -> str:
        return json.dumps(v) if quote else v

    body = ",\n".join(f'  "{k}": {val(v)}' for k, v in items.items())
    return f"${name}: (\n{body}\n);"


def write_scss(tokens: Tokens, out: Path) -> None:
    maps = [
        _scss_map("palette", {k: c.css for k, c in tokens.palette.items()}),
        _scss_map("breakpoints", tokens.breakpoints),
    ]
    for table in SCALAR_TABLES:
        maps.append(_scss_map(f"{table}-values", tokens.scalars[table], quote=True))
    theme_maps = []
    for name, theme in tokens.themes.items():
        theme_maps.append(_scss_map(f"theme-{name}", {k: c.css for k, c in theme.colors.items()}))
    names = ", ".join(f'"{n}"' for n in tokens.themes)
    color_names = ", ".join(f'"{k}"' for k in tokens.themes[tokens.default_theme].colors)
    text = "\n\n".join(
        [
            f"// {HEADER}",
            "// Usage: @use \"<relative>/brand/dist/tokens/tokens\" as t;",
            "// Values are runtime custom properties, so themes switch without a rebuild.",
            '@use "sass:map";\n@use "sass:list";',
            f"$themes: ({names});\n$color-names: ({color_names});",
            *maps,
            *theme_maps,
            (Path(__file__).parent / "scss_api.scss").read_text(encoding="utf-8").strip(),
            "// ---- custom properties (emitted once per compilation)",
            root_css(tokens),
        ]
    )
    out.write_text(text, encoding="utf-8")


def write_css(tokens: Tokens, out: Path) -> None:
    out.write_text(f"/* {HEADER} */\n\n" + root_css(tokens), encoding="utf-8")


def write_json(tokens: Tokens, out: Path) -> None:
    data = {
        "$comment": HEADER,
        "meta": tokens.meta,
        "palette": {k: c.css for k, c in tokens.palette.items()},
        "themes": {
            name: {
                "color": {
                    k: {"css": c.css, "hex": c.hex, "alpha": c.a, "on_bg": c.over(t.colors["bg"]).hex}
                    for k, c in t.colors.items()
                },
                "shadow": t.shadows,
            }
            for name, t in tokens.themes.items()
        },
        **{table: tokens.scalars[table] for table in SCALAR_TABLES},
        "breakpoint": tokens.breakpoints,
        "art": {"color": {k: c.css for k, c in tokens.art_colors.items()}, **tokens.art},
        "css_vars": css_vars(tokens),
    }
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def contrast_markdown(tokens: Tokens) -> str:
    rows = ["| Theme | Foreground | Background | Ratio | Min | Pass |", "|---|---|---|---|---|---|"]
    for r in contrast_report(tokens):
        rows.append(
            f"| {r.theme} | {r.fg} | {r.bg} | {r.ratio:.2f} | {r.minimum:g} | {'yes' if r.ok else 'NO'} |"
        )
    return "\n".join(rows) + "\n"


def contrast_summary(tokens: Tokens) -> str:
    """Lowest ratio per foreground and theme across the backgrounds of its rule."""
    themes = list(tokens.themes)
    worst: dict[tuple[str, str], tuple[float, str, float]] = {}
    for r in contrast_report(tokens):
        key = (r.fg, r.theme)
        if key not in worst or r.ratio < worst[key][0]:
            worst[key] = (r.ratio, r.bg, r.minimum)
    fgs = list(dict.fromkeys(fg for fg, _ in worst))
    rows = ["| Token | Min | " + " | ".join(themes) + " |", "|---|---|" + "---|" * len(themes)]
    for fg in fgs:
        cells = [f"{worst[(fg, t)][0]:.2f} on {worst[(fg, t)][1]}" for t in themes]
        rows.append(f"| {fg} | {worst[(fg, themes[0])][2]:g} | " + " | ".join(cells) + " |")
    return "\n".join(rows) + "\n"
