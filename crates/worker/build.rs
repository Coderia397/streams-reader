//! Embeds the two static builds into the Worker: the landing site (`crates/site/dist`, served at `/`) and the web app
//! (`crates/web/dist`, served under `/app/`). Every published file becomes an entry of a generated table, sorted by
//! URL path, with its content type, a sha256 ETag and its cache policy. A build that has not been made yet is replaced
//! by a placeholder page, so the Worker still builds and deploys.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

use sha2::{Digest, Sha256};

// The policy lives in the server crate, where it is unit-tested; it has no dependencies so it can be included here.
#[allow(dead_code)]
#[path = "../server/src/static_assets.rs"]
mod static_assets;
use static_assets::{APP_PREFIX, cache_control, content_type, is_published};

/// One static build and where it is served.
struct Bundle {
    /// Folder relative to this crate.
    dist: &'static str,
    /// URL prefix without the trailing slash ("" for the site).
    prefix: &'static str,
    /// What the placeholder says is missing.
    what: &'static str,
}

const BUNDLES: [Bundle; 2] = [
    Bundle { dist: "../site/dist", prefix: "", what: "The website" },
    Bundle { dist: "../web/dist", prefix: "/app", what: "The web app" },
];

fn placeholder(what: &str) -> String {
    format!(
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>Streams Reader</title></head>\
         <body><main><h1>Streams Reader</h1><p>{what} has not been built into this Worker yet.</p></main></body>\
         </html>\n"
    )
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let out = PathBuf::from(env::var("OUT_DIR").unwrap_or_default());
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../server/src/static_assets.rs");
    debug_assert_eq!(BUNDLES[1].prefix, APP_PREFIX.trim_end_matches('/'));

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    for bundle in &BUNDLES {
        let dist = manifest.join(bundle.dist);
        println!("cargo:rerun-if-changed={}", dist.display());
        if dist.join("index.html").is_file() {
            collect(&dist, &dist, bundle.prefix, &mut files);
        } else {
            let name = format!("placeholder{}.html", bundle.prefix.replace('/', "-"));
            let page = out.join(name);
            if let Err(e) = fs::write(&page, placeholder(bundle.what)) {
                println!("cargo:warning=cannot write placeholder: {e}");
            }
            println!("cargo:warning={} is not built; embedding a placeholder page", bundle.dist);
            files.push((format!("{}/index.html", bundle.prefix), page));
        }
    }
    files.sort();
    files.dedup_by(|a, b| a.0 == b.0);

    let mut code = String::from(
        "// Generated by build.rs from crates/site/dist and crates/web/dist; sorted by path.\n\
         pub static ASSETS: &[Asset] = &[\n",
    );
    for (path, file) in &files {
        let bytes = match fs::read(file) {
            Ok(b) => b,
            Err(e) => {
                println!("cargo:warning=cannot read {}: {e}", file.display());
                continue;
            }
        };
        let etag = format!("\"{}\"", &hex::encode(Sha256::digest(&bytes))[..32]);
        let _ = writeln!(
            code,
            "    Asset {{ path: {path:?}, content_type: {ct:?}, etag: {etag:?}, cache_control: {cc:?}, \
             body: include_bytes!({file:?}) }},",
            ct = content_type(path),
            cc = cache_control(path),
            file = file.display().to_string(),
        );
    }
    code.push_str("];\n");
    if let Err(e) = fs::write(out.join("assets.rs"), code) {
        println!("cargo:warning=cannot write assets.rs: {e}");
    }
}

/// Every published file under `dir`, as (URL path, file).
fn collect(root: &Path, dir: &Path, prefix: &str, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let Ok(rel) = path.strip_prefix(root) else { continue };
        let rel = rel.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/");
        if !is_published(&rel) {
            continue;
        }
        if path.is_dir() {
            collect(root, &path, prefix, out);
        } else {
            out.push((format!("{prefix}/{rel}"), path));
        }
    }
}
