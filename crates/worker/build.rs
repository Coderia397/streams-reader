//! Embeds the web app build (`crates/web/dist`) into the Worker: every file becomes an entry of a generated table with
//! its content type, a sha256 ETag and a cache policy. When the web app has not been built yet, a placeholder page is
//! embedded instead so the Worker still builds and deploys.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

use sha2::{Digest, Sha256};

// The policy lives in the server crate, where it is unit-tested; it has no dependencies so it can be included here.
#[path = "../server/src/static_assets.rs"]
mod static_assets;
use static_assets::{cache_control, content_type};

const PLACEHOLDER: &str = "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\
<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>nolabs</title></head>\
<body><main><h1>nolabs</h1><p>The web app has not been built into this Worker yet.</p></main></body></html>\n";

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_default());
    let out = PathBuf::from(env::var("OUT_DIR").unwrap_or_default());
    let dist = manifest.join("../web/dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../server/src/static_assets.rs");

    let mut files = Vec::new();
    if dist.join("index.html").is_file() {
        collect(&dist, &dist, &mut files);
    } else {
        let placeholder = out.join("placeholder-index.html");
        if let Err(e) = fs::write(&placeholder, PLACEHOLDER) {
            println!("cargo:warning=cannot write placeholder: {e}");
        }
        files.push(("/index.html".to_owned(), placeholder));
    }
    files.sort();

    let mut code = String::from("/// Generated by build.rs from crates/web/dist.\npub static ASSETS: &[Asset] = &[\n");
    for (path, file) in &files {
        let bytes = match fs::read(file) {
            Ok(b) => b,
            Err(e) => {
                println!("cargo:warning=cannot read {}: {e}", file.display());
                continue;
            }
        };
        let etag = format!("\"{}\"", &hex::encode(Sha256::digest(&bytes))[..32]);
        let _ = writeln!(
            code,
            "    Asset {{ path: {path:?}, content_type: {ct:?}, etag: {etag:?}, cache_control: {cc:?}, \
             body: include_bytes!({file:?}) }},",
            ct = content_type(path),
            cc = cache_control(path),
            file = file.display().to_string(),
        );
    }
    code.push_str("];\n");
    if let Err(e) = fs::write(out.join("assets.rs"), code) {
        println!("cargo:warning=cannot write assets.rs: {e}");
    }
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Ok(rel) = path.strip_prefix(root) {
            let url =
                format!("/{}", rel.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/"));
            out.push((url, path));
        }
    }
}
